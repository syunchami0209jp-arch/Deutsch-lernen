/* Enterキーでも回答・次へ進める */
document.addEventListener("keydown", event => {
  const practice = dq("verb-practice");
  if (!practice || practice.classList.contains("hidden")) return;

  if (event.key !== "Enter") return;

  const check = dq("verb-check");
  const next = dq("verb-next");

  if (check && !check.classList.contains("hidden")) {
    event.preventDefault();
    check.click();
  } else if (next && !next.classList.contains("hidden")) {
    event.preventDefault();
    next.click();
  }
});

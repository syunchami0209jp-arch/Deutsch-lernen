/* ---------- 文空欄補充 ---------- */

function getBlankSentence(v, mode) {
  if (mode === "present") {
    return v.presentExample.replace(v.du, "_____");
  }

  if (mode === "three") {
    return v.pastExample.replace(v.past, "_____");
  }

  return v.subjExample.replace("___", "_____");
}

function getCorrectAnswer(v, mode) {
  if (mode === "present") return v.du;
  if (mode === "three") return v.past;
  return v.subj2;
}

function getVerbChoices(v, mode) {
  const correct = getCorrectAnswer(v, mode);

  const distractors = verbData
    .filter(item => item.id !== v.id)
    .map(item => getCorrectAnswer(item, mode))
    .filter(answer => answer && answer !== correct);

  return shuffleVerbs([
    correct,
    ...shuffleVerbs(distractors).slice(0, 3)
  ]);
}

function renderVerbBlank(v, mode) {
  const answer = getCorrectAnswer(v, mode);

  dq("verb-practice-content").innerHTML = `
    <div class="verb-mode-label">${VERB_MODE_LABELS[mode]}</div>

    <div class="example">${getBlankSentence(v, mode)}</div>

    <p class="translation-small">意味：${v.japanese}</p>

    <div id="verb-options"></div>

    <div class="verb-result" id="verb-result"></div>

    <div class="action-area">
      <button class="primary hidden" id="verb-next">次の問題</button>
    </div>`;

  getVerbChoices(v, mode).forEach(choice => {
    const button = document.createElement("button");
    button.className = "option";
    button.textContent = choice;

    button.onclick = () => {
      const correct = choice === answer;

      verbScore.total++;
      if (correct) verbScore.correct++;

      dq("verb-result").innerHTML = correct
        ? `⭕ 正解！<br>正解：<b>${answer}</b>`
        : `❌ 不正解。正解は <b>${answer}</b> です。`;

      dq("verb-options")
        .querySelectorAll("button")
        .forEach(item => item.disabled = true);

      dq("verb-next").classList.remove("hidden");
      dq("verb-next").focus();
    };

    dq("verb-options").appendChild(button);
  });

  dq("verb-next").onclick = nextVerbQuestion;
}

/* ---------- タイピング ---------- */

function renderVerbTyping(v, mode) {
  const answer = getCorrectAnswer(v, mode);

  let instruction;

  if (mode === "present") {
    instruction = `${v.infinitive}（${v.japanese}）の du の形を入力してください。`;
  } else if (mode === "three") {
    instruction = `${v.infinitive}（${v.japanese}）の三基本形を入力してください。<br>
      <span class="small">不定詞 / 直説法過去 / 過去分詞</span>`;
  } else {
    instruction = `${v.infinitive}（${v.japanese}）の接続法Ⅱ式を入力してください。`;
  }

  dq("verb-practice-content").innerHTML = `
    <div class="verb-mode-label">${VERB_MODE_LABELS[mode]}</div>

    <div class="card">
      <div class="german">${v.infinitive}</div>
      <p>${instruction}</p>
    </div>

    <input id="verb-input" autocomplete="off" placeholder="ここに入力">

    <div class="special-keys-verb">
      <button type="button" data-char="ä">ä</button>
      <button type="button" data-char="ö">ö</button>
      <button type="button" data-char="ü">ü</button>
      <button type="button" data-char="ß">ß</button>
      <button type="button" data-char="Ä">Ä</button>
      <button type="button" data-char="Ö">Ö</button>
      <button type="button" data-char="Ü">Ü</button>
    </div>

    <div class="action-area">
      <button class="primary" id="verb-check">回答する</button>
      <button class="primary hidden" id="verb-next">次の問題</button>
    </div>

    <div class="verb-result" id="verb-result"></div>`;

  document.querySelectorAll(".special-keys-verb button").forEach(button => {
    button.onclick = () => {
      const input = dq("verb-input");
      const start = input.selectionStart ?? input.value.length;
      const end = input.selectionEnd ?? input.value.length;

      input.value =
        input.value.slice(0, start) +
        button.dataset.char +
        input.value.slice(end);

      input.focus();

      const newPosition = start + button.dataset.char.length;
      input.setSelectionRange(newPosition, newPosition);
    };
  });

  dq("verb-input").focus();

  dq("verb-check").onclick = () => {
    const userAnswer = normalizeVerbAnswer(dq("verb-input").value);
    const expected = normalizeVerbAnswer(answer);
    const correct = userAnswer === expected;

    verbScore.total++;
    if (correct) verbScore.correct++;

    dq("verb-input").disabled = true;
    dq("verb-check").classList.add("hidden");

    dq("verb-result").innerHTML = correct
      ? `⭕ 正解！<br>正解：<b>${answer}</b>`
      : `❌ 不正解。正解は <b>${answer}</b> です。`;

    dq("verb-next").classList.remove("hidden");
    dq("verb-next").focus();
  };

  dq("verb-next").onclick = nextVerbQuestion;
}

function normalizeVerbAnswer(text) {
  return text
    .trim()
    .toLowerCase()
    .replace(/\s+/g, " ");
}

function nextVerbQuestion() {
  verbIndex++;

  if (verbIndex >= verbQuestions.length) {
    finishVerbPractice();
  } else {
    renderVerbQuestion();
  }
}

function finishVerbPractice() {
  dq("verb-progress").textContent = "";

  dq("verb-practice-content").innerHTML = `
    <div class="card">
      <h2>練習終了！</h2>
      <p class="score">${verbScore.correct} / ${verbScore.total} 正解</p>

      <button class="primary" id="verb-again">もう一度</button>
      <button id="verb-menu-back">練習メニューへ</button>
    </div>`;

  dq("verb-again").onclick = () => startVerbPractice(verbQuestionType);

  dq("verb-menu-back").onclick = () => {
    if (verbMode === "all") {
      openVerbAll();
    } else {
      openVerbType(verbMode);
    }
  };
}


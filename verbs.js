let verbMode = "present";
let verbQuestionType = "card";
let verbQuestions = [];
let verbIndex = 0;
let verbScore = { correct: 0, total: 0 };
let currentVerbActualMode = "present";

const VERB_MODE_LABELS = {
  present: "直接法現在",
  three: "三基本形",
  subj2: "接続法Ⅱ式",
  all: "全て出題"
};

function dq(id) {
  return document.getElementById(id);
}

/* app.js の show() に依存しない、動詞ページ専用の画面切替 */
function verbShowScreen(id) {
  document.querySelectorAll(".screen").forEach(screen => {
    screen.classList.add("hidden");
  });

  const target = dq(id);
  if (target) {
    target.classList.remove("hidden");
    window.scrollTo(0, 0);
  } else {
    console.error("ドイツ語クエスト: 画面が見つかりません:", id);
  }
}

function openVerbPractice() {
  verbShowScreen("verb-menu");
}

function openVerbType(mode) {
  verbMode = mode;
  dq("verb-type-title").textContent = VERB_MODE_LABELS[mode] || mode;
  verbShowScreen("verb-types");
}

function openVerbAll() {
  verbMode = "all";
  dq("verb-type-title").textContent = "全て出題";
  verbShowScreen("verb-types");
}

function openVerbTable() {
  renderVerbTable();
  verbShowScreen("verb-table");
}

function shuffleVerbs(array) {
  const result = [...array];
  for (let i = result.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [result[i], result[j]] = [result[j], result[i]];
  }
  return result;
}

function chooseVerbMode() {
  if (verbMode !== "all") return verbMode;
  const modes = ["present", "three", "subj2"];
  return modes[Math.floor(Math.random() * modes.length)];
}

function startVerbPractice(type) {
  verbQuestionType = type;
  verbQuestions = shuffleVerbs(verbData);
  verbIndex = 0;
  verbScore = { correct: 0, total: 0 };

  verbShowScreen("verb-practice");
  renderVerbQuestion();
}

function renderVerbQuestion() {
  if (verbIndex >= verbQuestions.length) {
    finishVerbPractice();
    return;
  }

  const v = verbQuestions[verbIndex];
  currentVerbActualMode = chooseVerbMode();

  dq("verb-progress").innerHTML =
    `<div class="verb-progress-text">${verbIndex + 1} / ${verbQuestions.length}　・　${VERB_MODE_LABELS[currentVerbActualMode]}</div>`;

  if (verbQuestionType === "card") {
    renderVerbCard(v, currentVerbActualMode);
  } else if (verbQuestionType === "blank") {
    renderVerbBlank(v, currentVerbActualMode);
  } else {
    renderVerbTyping(v, currentVerbActualMode);
  }
}

